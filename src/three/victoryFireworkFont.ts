function patternToGrid(pattern: string): boolean[][] {
  const grid: boolean[][] = [];
  for (let row = 0; row < ROWS; row += 1) {
    const line = pattern.slice(row * COLS, row * COLS + COLS);
    grid.push([...line].map((cell) => cell === "#"));
  }
  return grid;
}

const GRIDS = new Map<string, boolean[][]>(
  Object.entries(PATTERNS).map(([char, pattern]) => [char, patternToGrid(pattern)]),
);

export function normalizeNameForFireworks(name: string): string {
  const stripped = name
    .normalize("NFD")
    .replace(/\p{M}/gu, "")
    .toUpperCase()
    .replace(/[^A-Z0-9 ]/g, " ")
    .replace(/\s+/g, " ")
    .trim();

  return stripped.length > 0 ? stripped : "WIN";
}

export function getLetterDots(char: string): Array<[number, number]> {
  const grid = GRIDS.get(char) ?? GRIDS.get("?") ?? [];
  const dots: Array<[number, number]> = [];

  for (let row = 0; row < grid.length; row += 1) {
    for (let col = 0; col < COLS; col += 1) {
      if (grid[row]?.[col]) {
        dots.push([col - (COLS - 1) / 2, (ROWS - 1) / 2 - row]);
      }
    }
  }

  return dots;
}

